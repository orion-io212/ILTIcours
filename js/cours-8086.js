// 4. مؤشرات الحساب (Flags Simulation)
function flags() {
  const a = +$("fa").value & 255;
  const b = +$("fb").value & 255;
  const add = $("fo").value == "+";
  const raw = add ? a + b : a - b;
  const r = raw & 255;
  
  const cf = add ? raw > 255 : a < b;
  const zf = r == 0;
  const sf = (r >> 7) & 1;
  const of = add ? !!((a ^ r) & (b ^ r) & 128) : !!((a ^ b) & (a ^ r) & 128);
  
  $("fr").innerHTML = [...r.toString(2).padStart(8, "0")].map((x) => `
    <span class="bt ${x == "1" ? "o" : ""}">${x}</span>
  `).join("") + `<span class="m" style="margin-left:10px;align-self:center">résultat = ${r} (0x${hx(r, 2)})</span>`;
  
  const L = [
    ["CF", cf, "Retenue : le résultat non signé ne tient pas sur 8 bits."],
    ["ZF", zf, "Zéro : le résultat est nul (en SUB, les opérandes étaient égaux)."],
    ["SF", !!sf, "Signe : le bit de poids fort du résultat vaut 1."],
    ["OF", of, "Débordement : le résultat signé ne tient pas dans la destination."]
  ];
  
  $("fl").innerHTML = L.map((x) => `
    <div class="chip ${x[1] ? "on" : ""}">
      <b class="m">${x[0]} = ${+x[1]}</b>
      <small>${x[2]}</small>
    </div>
  `).join("");
}

["fa", "fb", "fo"].forEach((i) => $(i).addEventListener("input", flags));
flags();

