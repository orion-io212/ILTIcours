// 6. دورة المعالج MIPS (MIPS Cycle)
(function () {
  const ch = [...document.querySelectorAll("#cyc .chip")];
  let i = 0;
  let pc = 0x400000;
  
  function t() {
    ch.forEach((c, k) => c.classList.toggle("on", k == i));
    if (i == 1) {
      pc += 4;
      $("pc").textContent = "0x" + hx(pc, 8);
    }
    i = (i + 1) % 3;
  }
  
  t();
  if (!matchMedia("(prefers-reduced-motion:reduce)").matches) {
    setInterval(t, 1400);
  }
})();

// 7. حساب المتمم إلى 2 (Two's Complement)
function c2() {
  let v = Math.max(-128, Math.min(127, parseInt($("cv").value) || 0));
  let u = v & 255;
  let b = u.toString(2).padStart(8, "0");
  
  $("cb").innerHTML = [...b].map((x) => `
    <span class="bt ${x == "1" ? "o" : ""}">${x}</span>
  `).join("");
  
  const m = Math.abs(v);
  const mb = m.toString(2).padStart(8, "0");
  const inv = (~m & 255).toString(2).padStart(8, "0");
  
  $("cs").innerHTML = v < 0 
    ? `|${v}| = ${mb}, inversion = ${inv}, +1 = ${b} (0x${hx(u, 2)}). Le bit de poids fort vaut 1 : le nombre est négatif.`
    : `Nombre positif : le bit de poids fort vaut 0 (0x${hx(u, 2)}).`;
}

$("cv").addEventListener("input", c2);
c2();