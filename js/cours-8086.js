const $ = (id) => document.getElementById(id);
const hx = (n, l) => n.toString(16).toUpperCase().padStart(l, "0");

// 1. حساب العنوان الفيزيائي
function calc() {
  let s = parseInt($("seg").value, 16);
  let o = parseInt($("off").value, 16);
  
  if (isNaN(s) || isNaN(o)) {
    $("phys").textContent = "Entrez deux valeurs hexadécimales";
    return;
  }
  
  s &= 0xFFFF;
  o &= 0xFFFF;
  const p = (s * 16 + o) & 0xFFFFF;
  const S = hx(s, 4) + "0";
  const O = "0" + hx(o, 4);
  const P = hx(p, 5);
  
  const row = (t, d, c) => `
    <div class="digits">
      <span class="t">${t}</span>
      ${[...d].map((x, i) => `<span class="dg ${c(i)}">${x}</span>`).join("")}
    </div>
  `;
  
  $("dig").innerHTML = row("Segment ×16", S, (i) => i == 4 ? "z" : "") +
                       row("+ Offset", O, (i) => i == 0 ? "z" : "") +
                       row("= Physique", P, () => "r");
                       
  $("phys").textContent = hx(s, 4) + ":" + hx(o, 4) + " → " + P + "h";
}

$("go").onclick = calc;
["seg", "off"].forEach((i) => $(i).addEventListener("input", calc));
calc();

